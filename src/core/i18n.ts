export const dictionaries: Record<Lang, Dictionary> = { fr, en };

export const localize = (value: Localized, lang: Lang): string => value[lang];

export function formatTime(epochMs: number, lang: Lang): string {
  return new Intl.DateTimeFormat(lang === 'fr' ? 'fr-FR' : 'en-GB', { hour: '2-digit', minute: '2-digit' }).format(
    epochMs,
  );
}

export function countryName(code: string, lang: Lang): string {
  if (!code) return '';
  try {
    return new Intl.DisplayNames([lang], { type: 'region' }).of(code.toUpperCase()) ?? code;
  } catch {
    return code;
  }
}
